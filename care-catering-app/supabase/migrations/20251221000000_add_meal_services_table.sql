-- Create meal_services table for managing meal service times
CREATE TABLE meal_services (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  code TEXT NOT NULL UNIQUE,
  service_time TIME NOT NULL,
  description TEXT,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Create index on code for faster lookups
CREATE INDEX IF NOT EXISTS idx_meal_services_code ON meal_services(code);
CREATE INDEX IF NOT EXISTS idx_meal_services_is_active ON meal_services(is_active);

-- Add trigger to update updated_at automatically
DROP TRIGGER IF EXISTS trg_meal_services_updated_at ON meal_services;
CREATE TRIGGER trg_meal_services_updated_at
BEFORE UPDATE ON meal_services
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Enable RLS
ALTER TABLE meal_services ENABLE ROW LEVEL SECURITY;

-- Policy: Only admins can read meal_services
CREATE POLICY "Admin read meal services" ON meal_services
  FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM profiles 
      WHERE id = auth.uid() AND role = 'admin'
    )
  );

