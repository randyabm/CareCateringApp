-- Create location_products table (Stock per location)
CREATE TABLE IF NOT EXISTS location_products (
    id bigint generated by default as identity primary key,
    location_id bigint REFERENCES locations(id) ON DELETE CASCADE NOT NULL,
    product_id bigint REFERENCES products(id) ON DELETE CASCADE NOT NULL,
    par_level int DEFAULT 0 NOT NULL,
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
    UNIQUE(location_id, product_id)
);

-- Create templates table
CREATE TABLE IF NOT EXISTS templates (
    id bigint generated by default as identity primary key,
    name text NOT NULL,
    description text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Create template_items table
CREATE TABLE IF NOT EXISTS template_items (
    id bigint generated by default as identity primary key,
    template_id bigint REFERENCES templates(id) ON DELETE CASCADE NOT NULL,
    product_id bigint REFERENCES products(id) ON DELETE CASCADE NOT NULL,
    default_par_level int DEFAULT 0 NOT NULL,
    UNIQUE(template_id, product_id)
);
