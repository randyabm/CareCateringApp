-- Create product_categories table
CREATE TABLE IF NOT EXISTS product_categories (
    id bigint generated by default as identity primary key,
    name text not null unique,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Add category_id to products
ALTER TABLE products ADD COLUMN IF NOT EXISTS category_id bigint REFERENCES product_categories(id);

-- Migrate existing categories
INSERT INTO product_categories (name)
SELECT DISTINCT category 
FROM products 
WHERE category IS NOT NULL AND category != ''
ON CONFLICT (name) DO NOTHING;

-- Update products to link to new categories
UPDATE products p
SET category_id = c.id
FROM product_categories c
WHERE p.category = c.name;

-- Note: We are keeping the 'category' text column for backwards compatibility for now, 
-- but it should be considered deprecated.
