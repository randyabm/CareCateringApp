-- Create Enums
CREATE TYPE user_role AS ENUM ('nurse', 'kitchen_staff', 'store_man', 'admin');
CREATE TYPE order_type AS ENUM ('grocery', 'catering', 'proactive_restock');
CREATE TYPE order_status AS ENUM ('pending', 'approved', 'processing', 'delivered', 'cancelled');
CREATE TYPE diet_category AS ENUM ('primary_diet', 'allergy', 'dislike');

-- PROFILES (Extends Supabase Auth Users)
CREATE TABLE profiles (
  id UUID REFERENCES auth.users(id) PRIMARY KEY,
  full_name TEXT,
  role user_role DEFAULT 'nurse',
  assigned_location_id INTEGER, -- FK added later after locations table
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- LOCATIONS (Wards, Kitchen, etc.)
CREATE TABLE locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  responsible_name TEXT,
  approver_email TEXT,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Add foreign key to profiles
ALTER TABLE profiles 
ADD CONSTRAINT fk_profile_location 
FOREIGN KEY (assigned_location_id) REFERENCES locations(id);

-- PRODUCTS
CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  unit_price DECIMAL(10, 2) DEFAULT 0.00,
  requires_approval BOOLEAN DEFAULT FALSE,
  category TEXT, -- e.g., 'Dairy', 'Medical', 'Stationery'
  image_url TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- LOCATION_PRODUCTS (Par Levels / Catalog)
CREATE TABLE location_products (
  location_id BIGINT REFERENCES locations(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id) ON DELETE CASCADE,
  par_level INTEGER DEFAULT 0,
  current_stock INTEGER DEFAULT 0, -- For gap analysis
  is_visible BOOLEAN DEFAULT TRUE,
  PRIMARY KEY (location_id, product_id)
);

-- DIET_CODES (Unified Diet Logic)
CREATE TABLE diet_codes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE, -- e.g., 'GF', 'DBT'
  name TEXT NOT NULL,
  category diet_category NOT NULL,
  description TEXT,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ORDERS
CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES profiles(id),
  location_id BIGINT REFERENCES locations(id),
  type order_type NOT NULL,
  status order_status DEFAULT 'pending',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ORDER_ITEMS (For Groceries)
CREATE TABLE order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT REFERENCES orders(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id),
  quantity INTEGER NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- CATERING_DETAILS (For Patient Food)
CREATE TABLE catering_details (
  order_id BIGINT REFERENCES orders(id) ON DELETE CASCADE PRIMARY KEY,
  primary_diet_id BIGINT REFERENCES diet_codes(id),
  bed_number TEXT NOT NULL,
  patient_name TEXT, -- Optional, for safety
  other_notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ORDER_DIETARY_FLAGS (Many-to-Many for Allergies/Dislikes)
CREATE TABLE order_dietary_flags (
  order_id BIGINT REFERENCES orders(id) ON DELETE CASCADE,
  diet_code_id BIGINT REFERENCES diet_codes(id) ON DELETE CASCADE,
  PRIMARY KEY (order_id, diet_code_id)
);

-- TEMPLATES (For Mass Setup)
CREATE TABLE setup_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, -- e.g., "Standard Surgical Ward Kit"
  description TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE template_items (
  template_id BIGINT REFERENCES setup_templates(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id) ON DELETE CASCADE,
  default_par_level INTEGER DEFAULT 0,
  PRIMARY KEY (template_id, product_id)
);

-- RLS POLICIES (Examples)
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;

-- Nurse can see orders from their location
CREATE POLICY "Nurse view own location orders" ON orders
  FOR SELECT
  USING (
    location_id IN (
      SELECT assigned_location_id FROM profiles 
      WHERE id = auth.uid()
    )
  );

-- Store Man can see all orders
CREATE POLICY "Store man view all orders" ON orders
  FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM profiles 
      WHERE id = auth.uid() AND role = 'store_man'
    )
  );
